package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"
	"time"
)

// SaveCrawl puts the crawl of an app into that app's own repo (hydra/crawl/), on a review branch like every other
// delivery. Each stored crawl is a commit whose message says what changed since the previous one, so `git log` of the
// folder is the history of how the app's UI moved. Identical crawls are not stored (the timestamp alone is not news).

type crawlDoc struct {
	BaseURL   string `json:"baseUrl"`
	CrawledAt string `json:"crawledAt"`
	Pages     []struct {
		URL      string         `json:"url"`
		Title    string         `json:"title"`
		Elements []CrawlElement `json:"elements"`
	} `json:"pages"`
}

func loadCrawlDoc(b []byte) (*crawlDoc, error) {
	d := &crawlDoc{}
	return d, json.Unmarshal(b, d)
}

func pathOf(url string) string {
	if i := strings.Index(url, "://"); i >= 0 {
		url = url[i+3:]
	}
	if i := strings.Index(url, "/"); i >= 0 {
		return url[i:]
	}
	return "/"
}

// sameCrawl: equal apart from the timestamp.
func sameCrawl(a, b []byte) bool {
	var x, y map[string]any
	if json.Unmarshal(a, &x) != nil || json.Unmarshal(b, &y) != nil {
		return false
	}
	delete(x, "crawledAt")
	delete(y, "crawledAt")
	return reflect.DeepEqual(x, y)
}

func locatorSet(d *crawlDoc) map[string]bool {
	s := map[string]bool{}
	for _, p := range d.Pages {
		for _, e := range p.Elements {
			s[pathOf(p.URL)+" "+e.Locator] = true
		}
	}
	return s
}

// crawlChange says what moved between two crawls, in a line a person can read in `git log`.
func crawlChange(old, cur *crawlDoc) string {
	if old == nil {
		return fmt.Sprintf("first crawl: %d pages, %d elements", len(cur.Pages), countEls(cur))
	}
	op, cp := map[string]bool{}, map[string]bool{}
	for _, p := range old.Pages {
		op[pathOf(p.URL)] = true
	}
	for _, p := range cur.Pages {
		cp[pathOf(p.URL)] = true
	}
	var added, removed []string
	for p := range cp {
		if !op[p] {
			added = append(added, p)
		}
	}
	for p := range op {
		if !cp[p] {
			removed = append(removed, p)
		}
	}
	sort.Strings(added)
	sort.Strings(removed)
	ol, cl := locatorSet(old), locatorSet(cur)
	plus, minus := 0, 0
	for k := range cl {
		if !ol[k] {
			plus++
		}
	}
	for k := range ol {
		if !cl[k] {
			minus++
		}
	}
	s := fmt.Sprintf("%d pages, %d elements; locators +%d -%d", len(cur.Pages), countEls(cur), plus, minus)
	if len(added) > 0 {
		s += "; new pages: " + strings.Join(added, ", ")
	}
	if len(removed) > 0 {
		s += "; pages gone: " + strings.Join(removed, ", ")
	}
	return s
}

func countEls(d *crawlDoc) (n int) {
	for _, p := range d.Pages {
		n += len(p.Elements)
	}
	return
}

// CrawlSummary is the page a person reads: what exists, and which locators are weak (to ask for a data-testid).
func CrawlSummary(app string, d *crawlDoc) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Crawl of %s\n\nGenerated by HydraPloy (`hydra crawl`), read-only. Do not edit by hand; the next crawl replaces it.\n\n", app)
	fmt.Fprintf(&b, "- Base URL when crawled: %s\n- Crawled at: %s\n- %d pages, %d elements\n\n", d.BaseURL, d.CrawledAt, len(d.Pages), countEls(d))
	b.WriteString("| Page | Title | Elements | Stable | Weak |\n|---|---|---|---|---|\n")
	var weak []string
	for _, p := range d.Pages {
		st, wk := 0, 0
		for _, e := range p.Elements {
			if e.Stable {
				st++
			} else {
				wk++
				weak = append(weak, fmt.Sprintf("- `%s` %s %q → `%s`", pathOf(p.URL), e.Role, e.Name, e.Locator))
			}
		}
		fmt.Fprintf(&b, "| `%s` | %s | %d | %d | %d |\n", pathOf(p.URL), p.Title, len(p.Elements), st, wk)
	}
	b.WriteString("\nStable = a unique `data-testid`, a stable id, or role + accessible name. Weak = not unique or only a CSS fallback.\n")
	if len(weak) > 0 {
		b.WriteString("\n## Weak locators (candidates for a `data-testid` in the app)\n\n")
		if len(weak) > 40 {
			weak = append(weak[:40], fmt.Sprintf("- … and %d more (see crawl.json)", len(weak)-40))
		}
		b.WriteString(strings.Join(weak, "\n") + "\n")
	}
	return b.String()
}

type Stored struct {
	Branch string `json:"branch,omitempty"`
	Commit string `json:"commit,omitempty"`
	Change string `json:"change,omitempty"`
	Note   string `json:"note,omitempty"`
}

func (c Config) SaveCrawl() (Stored, error) {
	var s Stored
	repo, base := expand(c.DeliverRepo), c.BaseBranch
	if !fileExists(filepath.Join(repo, ".git")) {
		return s, fmt.Errorf("%s is not a repo yet: run hydra onboard --project <KEY> first", repo)
	}
	ensureIgnored(repo)
	if st, e := git(repo, "status", "--porcelain"); e != nil || st != "" {
		return s, fmt.Errorf("the repo must be clean before storing a crawl (%q %v)", st, e)
	}
	cur, err := os.ReadFile(c.crawlPath())
	if err != nil {
		return s, fmt.Errorf("no crawl to store (%v): run hydra crawl first", err)
	}
	doc, err := loadCrawlDoc(cur)
	if err != nil {
		return s, err
	}
	rel := filepath.Join("hydra", "crawl")
	// "the last stored crawl" is the newest crawl branch if there is one (merged or still awaiting review), else the base branch:
	// a crawl waiting for review is already stored, and storing it again would only pile up identical branches.
	ref, where := base, "the base branch"
	if latest, e := git(repo, "for-each-ref", "--sort=-creatordate", "--count=1", "--format=%(refname:short)", "refs/heads/hydra/crawl-"+appSlug(c.App)+"-*"); e == nil && latest != "" {
		ref, where = latest, "branch "+latest
	}
	prev, perr := git(repo, "show", ref+":"+filepath.ToSlash(filepath.Join(rel, "crawl.json")))
	var old *crawlDoc
	if perr == nil {
		if sameCrawl([]byte(prev), cur) {
			s.Note = "unchanged since the last stored crawl (" + where + "): nothing to store"
			return s, nil
		}
		old, _ = loadCrawlDoc([]byte(prev))
	}
	s.Change = crawlChange(old, doc)

	s.Branch = uniqueBranch(repo, fmt.Sprintf("hydra/crawl-%s-%s", appSlug(c.App), time.Now().Format("20060102-150405")))
	if _, err = git(repo, "checkout", "-q", "-b", s.Branch, base); err != nil {
		return s, err
	}
	restore := func() {
		git(repo, "reset", "--hard", "-q")
		git(repo, "clean", "-fdq")
		git(repo, "checkout", "-q", base)
		git(repo, "branch", "-D", "-q", s.Branch)
	}
	dir := filepath.Join(repo, rel)
	os.MkdirAll(dir, 0o755)
	if err = os.WriteFile(filepath.Join(dir, "crawl.json"), cur, 0o644); err == nil {
		err = os.WriteFile(filepath.Join(dir, "CRAWL.md"), []byte(CrawlSummary(c.App, doc)), 0o644)
	}
	if err == nil {
		_, err = git(repo, "add", rel)
	}
	if err == nil {
		_, err = git(repo, append(gitIdentity(repo), "commit", "-q", "-m", "hydra: crawl of "+c.App+" ("+s.Change+")\n\nRead-only crawl of "+doc.BaseURL+". Replaces hydra/crawl/.")...)
	}
	if err != nil {
		restore()
		return Stored{}, err
	}
	s.Commit, _ = git(repo, "rev-parse", "--short", "HEAD")
	git(repo, "checkout", "-q", base)
	return s, nil
}
